'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'www/index.html'), 'utf8');
const library = fs.readFileSync(path.join(root, 'www/booksup-library.js'), 'utf8');
const vm = require('node:vm');
const core = html.match(/const copyEdition=e=>[^\n]*\nconst editionsOf=b=>[^\n]*\nfunction unifyBookEd\(b\)[^\n]*\nfunction mergePhysical\(book\)[^\n]*/);
assert.ok(core, 'physical price helpers missing');
assert.match(library, /inputmode="decimal" type="text"/);
assert.match(html, /id="ee_\$\{i\}_purchasePrice"/);
const S = {books:[]};
const number = v => v==null || String(v).trim()==='' ? null : Number.isFinite(Number(String(v).replace(',','.'))) ? Math.round(Number(String(v).replace(',','.'))*100)/100 : null;
const context = {S, buSafeNumber:number, isbnClean:v=>String(v||''), cov0:()=>null, uniqueCovers:xs=>[...new Set(xs.filter(Boolean))], norm:v=>String(v||'').toLowerCase().trim()};
vm.runInNewContext(core[0]+';globalThis.prices={copyEdition,editionsOf,unifyBookEd,mergePhysical}',context);
const make=(purchasePrice,price,qty=1)=>({type:'physical',title:'Same book',author:'Writer',purchasePrice,price,msrp:price,qty,covers:[]});
context.prices.mergePhysical(make('5,50',20));
context.prices.mergePhysical(make('7,50',22));
assert.equal(S.books.length,1);
assert.equal(S.books[0].purchasePrice,6.5);
assert.equal(S.books[0].editions[0].purchasePrice,5.5);
assert.equal(S.books[0].editions[1].purchasePrice,7.5);
assert.equal(S.books[0].msrp,20);
const legacy={...make(4.2,20),editions:[{price:20,qty:1,format:'Hardcover'}]};
context.prices.unifyBookEd(legacy);
assert.equal(legacy.purchasePrice,4.2);
assert.equal(legacy.editions[0].purchasePrice,4.2);
console.log('OK: comma-price input and physical-edition purchase prices');
